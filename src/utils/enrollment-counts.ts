import { and, countDistinct, desc, eq, inArray, sql } from "drizzle-orm";
import type { getDb } from "@/db";
import type { DataAccess } from "@/utils/data-access";
import { courses, faculty, programs, studentCourses, studentPrograms } from "@/db/schema";
import { STUDENT_COURSE_ROW, STUDENT_PROGRAM_ROW } from "@/utils/data-access";

type Db = ReturnType<typeof getDb>;

export type EnrollmentTerm = { year: number; term_id: string };

// Registered, web registered and reinstated. Drops, withdrawals, cancellations and audits don't count as enrolled.
export const ENROLLED_STATUSES = ["RE", "RW", "RC"];

// Every count below is for one term, in one department, and only over rows the viewer can see
function enrolledInDepartment(access: DataAccess, departmentId: string, term: EnrollmentTerm) {
  return and(
    eq(courses.department_id, departmentId),
    eq(studentCourses.year, term.year),
    eq(studentCourses.term_id, term.term_id),
    inArray(studentCourses.registration_status_id, ENROLLED_STATUSES),
    access.canSee("courses", STUDENT_COURSE_ROW),
  );
}

function inDepartmentPrograms(access: DataAccess, departmentId: string, term: EnrollmentTerm) {
  return and(
    eq(programs.department_id, departmentId),
    eq(studentPrograms.year, term.year),
    eq(studentPrograms.term_id, term.term_id),
    access.canSee("programs", STUDENT_PROGRAM_ROW),
  );
}

// sum() is null when there are no rows, so it's 0 instead
const creditHours = sql<number>`coalesce(sum(${studentCourses.course_hours}), 0)`.mapWith(Number);

// A section is a course and section number together, since section "01" exists in many courses
const sectionKey = sql`concat(${studentCourses.course_id}, '-', ${studentCourses.course_section})`;

/**
 * The terms the department has enrollments in, newest first.
 */
export async function getEnrollmentTerms(db: Db, access: DataAccess, departmentId: string) {
  return db
    .selectDistinct({ year: studentCourses.year, term_id: studentCourses.term_id })
    .from(studentCourses)
    .innerJoin(courses, eq(studentCourses.course_id, courses.id))
    .where(
      and(
        eq(courses.department_id, departmentId),
        inArray(studentCourses.registration_status_id, ENROLLED_STATUSES),
        access.canSee("courses", STUDENT_COURSE_ROW),
      ),
    )
    .orderBy(desc(studentCourses.year), desc(studentCourses.term_id));
}

/**
 * The department's totals for a term.
 * - students: different students taking the department's courses
 * - majors: different students with a major in the department's programs
 */
export async function getEnrollmentSummary(
  db: Db,
  access: DataAccess,
  departmentId: string,
  term: EnrollmentTerm,
) {
  const [courseTotals] = await db
    .select({
      students: countDistinct(studentCourses.mnumber),
      credit_hours: creditHours,
      sections: countDistinct(sectionKey),
    })
    .from(studentCourses)
    .innerJoin(courses, eq(studentCourses.course_id, courses.id))
    .where(enrolledInDepartment(access, departmentId, term));

  const [programTotals] = await db
    .select({ majors: countDistinct(studentPrograms.mnumber) })
    .from(studentPrograms)
    .innerJoin(programs, eq(studentPrograms.program_id, programs.id))
    .where(
      and(inDepartmentPrograms(access, departmentId, term), eq(studentPrograms.type, "MAJOR")),
    );

  return {
    students: courseTotals.students,
    credit_hours: courseTotals.credit_hours,
    sections: courseTotals.sections,
    majors: programTotals.majors,
  };
}

/**
 * Each department course taught in the term.
 * - enrolled: seats taken, so a student in two sections counts twice
 * - credit_hours: the hours of every seat added up (30 students in a 3 hour course is 90)
 */
export async function getCourseEnrollments(
  db: Db,
  access: DataAccess,
  departmentId: string,
  term: EnrollmentTerm,
) {
  return db
    .select({
      course_id: studentCourses.course_id,
      title: courses.title,
      hours: courses.hours,
      enrolled: sql<number>`count(*)`.mapWith(Number),
      sections: countDistinct(studentCourses.course_section),
      credit_hours: creditHours,
    })
    .from(studentCourses)
    .innerJoin(courses, eq(studentCourses.course_id, courses.id))
    .where(enrolledInDepartment(access, departmentId, term))
    .groupBy(studentCourses.course_id, courses.title, courses.hours)
    .orderBy(studentCourses.course_id);
}

/**
 * Each instructor teaching the department's courses in the term, whichever department they belong to.
 * - enrolled: seats across all their sections
 * - credit_hours: the hours generated by those seats
 */
export async function getInstructorEnrollments(
  db: Db,
  access: DataAccess,
  departmentId: string,
  term: EnrollmentTerm,
) {
  return db
    .select({
      mnumber: studentCourses.instructor_mnumber,
      first_name: faculty.first_name,
      last_name: faculty.last_name,
      enrolled: sql<number>`count(*)`.mapWith(Number),
      sections: countDistinct(sectionKey),
      credit_hours: creditHours,
    })
    .from(studentCourses)
    .innerJoin(courses, eq(studentCourses.course_id, courses.id))
    .innerJoin(faculty, eq(studentCourses.instructor_mnumber, faculty.mnumber))
    .where(enrolledInDepartment(access, departmentId, term))
    .groupBy(studentCourses.instructor_mnumber, faculty.first_name, faculty.last_name)
    .orderBy(faculty.last_name, faculty.first_name);
}

/**
 * Each department program with students in the term, as majors and as minors.
 */
export async function getProgramEnrollments(
  db: Db,
  access: DataAccess,
  departmentId: string,
  term: EnrollmentTerm,
) {
  return db
    .select({
      program_id: studentPrograms.program_id,
      description: programs.description,
      majors:
        sql<number>`count(distinct case when ${studentPrograms.type} = 'MAJOR' then ${studentPrograms.mnumber} end)`.mapWith(
          Number,
        ),
      minors:
        sql<number>`count(distinct case when ${studentPrograms.type} = 'MINOR' then ${studentPrograms.mnumber} end)`.mapWith(
          Number,
        ),
    })
    .from(studentPrograms)
    .innerJoin(programs, eq(studentPrograms.program_id, programs.id))
    .where(inDepartmentPrograms(access, departmentId, term))
    .groupBy(studentPrograms.program_id, programs.description)
    .orderBy(studentPrograms.program_id);
}
